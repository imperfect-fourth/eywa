package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/types"
	"os"
	re "regexp"
	"strings"

	"golang.org/x/tools/go/packages"
)

var (
	typeNames  = flag.String("types", "", "comma-separated list of type names; must be set")
	outputFile = flag.String("output-file", "eywa_generated.go", "output file path for generated file.")
)

func usage() {
	fmt.Fprint(os.Stderr, "Usage:")
	fmt.Fprint(os.Stderr, "\teywagen -types <comma separated list of type names>")
}

var tagPattern = re.MustCompile(`json:"([^"]+)"`)

const (
	genHeader         = "// generated by eywa. DO NOT EDIT. Any changes will be overwritten.\npackage "
	scalarFieldFormat = "var %s = eywa.NewField[%s](\"%s\")\n"
	objectFieldFormat = "var %s = eywa.NewObjectField[%s, %s](\"%s\")\n"
	argumentFormat    = "var %s = eywa.NewArgument[%s, %s](\"%s\")\n"
)

func main() {
	flag.Usage = usage
	flag.Parse()
	if *typeNames == "" {
		flag.Usage()
		os.Exit(2)
	}
	types := strings.Split(*typeNames, ",")

	pkg, err := loadPackage(".")
	if err != nil {
		panic(err)
	}

	if err := loadEywaInterfaces(); err != nil {
		panic(err)
	}

	header := bytes.NewBufferString(genHeader)
	header.WriteString(pkg.Name())
	header.WriteString("\n")

	contents := &fileContent{
		header:     header,
		importsMap: map[string]bool{"github.com/imperfect-fourth/eywa": true},
		imports:    bytes.NewBuffer([]byte{}),
		content:    bytes.NewBufferString(""),
	}
	for _, t := range types {
		if err := parseType(t, pkg, contents); err != nil {
			panic(err)
		}
	}
	if len(contents.importsMap) > 0 {
		contents.imports.WriteString("\nimport (\n")
		for pkgImport, ok := range contents.importsMap {
			if ok {
				fmt.Fprintf(contents.imports, "\t\"%s\"\n", pkgImport)
			}
		}
		contents.imports.WriteString(")\n\n")
	}
	if err := writeToFile(*outputFile, contents); err != nil {
		fmt.Fprint(os.Stderr, err.Error())
		os.Exit(1)
	}
}

type fileContent struct {
	header     *bytes.Buffer
	importsMap map[string]bool
	imports    *bytes.Buffer
	content    *bytes.Buffer
}

var parsed = make(map[string]bool)

func parseType(typeName string, pkg *types.Package, contents *fileContent) error {
	typeObj := pkg.Scope().Lookup(typeName).Type()
	if typeObj == nil {
		fmt.Printf("type %s not found in package, skipping...\n", typeName)
		return nil
	}
	typeStruct, ok := typeObj.Underlying().(*types.Struct)
	if !ok {
		fmt.Printf("type %s is not a struct, skipping...\n", typeName)
		return nil
	}

	if types.Implements(typeObj, selSetInterface) {
		fmt.Printf("type %s implements eywa.SelectionSet interface\n", typeName)
		return parseSelectionSet(typeName, pkg, contents, typeStruct)
	} else if types.Implements(typeObj, argSetInterface) {
		fmt.Printf("type %s implements eywa.Arguments interface\n", typeName)
		return parseArguments(typeName, pkg, contents, typeStruct)
	}
	return nil
}

func parseArguments(typeName string, pkg *types.Package, contents *fileContent, typeStruct *types.Struct) error {
	if parsed[typeName] {
		return nil
	}
	parsed[typeName] = true

	contents.content.WriteString("\n")
	for i := 0; i < typeStruct.NumFields(); i++ {
		tag := tagPattern.FindStringSubmatch(typeStruct.Tag(i))
		if tag == nil {
			continue
		}
		tagValues := strings.Split(tag[1], ",")
		if len(tagValues) == 0 {
			continue
		}
		fieldName := tagValues[0]
		//		contents.importsMap["fmt"] = true
		field := typeStruct.Field(i)
		if !field.Exported() {
			continue
		}
		fieldType := field.Type()

		// *struct -> struct, *[] -> [], *int -> int, etc
		if ptr, ok := fieldType.(*types.Pointer); ok {
			fieldType = ptr.Elem()
		}
		// []*x -> *x, []x -> x
		if slice, ok := fieldType.(*types.Slice); ok {
			fieldType = slice.Elem()
		} else if array, ok := fieldType.(*types.Array); ok {
			fieldType = array.Elem()
		}

		importPackages, packageLocalName := parseFieldTypeName(fieldType.String(), pkg.Path())
		for _, p := range importPackages {
			contents.importsMap[p] = true
		}

		fmt.Fprintf(
			contents.content,
			argumentFormat,
			fmt.Sprintf("%s_%s", typeName, field.Name()),
			typeName,
			packageLocalName,
			fieldName,
		)
	}
	return nil
}

func parseSelectionSet(typeName string, pkg *types.Package, contents *fileContent, typeStruct *types.Struct) error {
	if parsed[typeName] {
		return nil
	}
	parsed[typeName] = true

	recurseParse := map[string]*types.Struct{}
	contents.content.WriteString("\n")
	for i := 0; i < typeStruct.NumFields(); i++ {
		tag := tagPattern.FindStringSubmatch(typeStruct.Tag(i))
		if tag == nil {
			continue
		}
		tagValues := strings.Split(tag[1], ",")
		if len(tagValues) == 0 {
			continue
		}
		fieldName := tagValues[0]
		field := typeStruct.Field(i)
		if !field.Exported() {
			continue
		}
		fieldType := field.Type()

		// *struct -> struct, *[] -> [], *int -> int, etc
		if ptr, ok := fieldType.(*types.Pointer); ok {
			fieldType = ptr.Elem()
		}
		// []*x -> *x, []x -> x
		if slice, ok := fieldType.(*types.Slice); ok {
			fieldType = slice.Elem()
		} else if array, ok := fieldType.(*types.Array); ok {
			fieldType = array.Elem()
		}

		importPackages, packageLocalName := parseFieldTypeName(fieldType.String(), pkg.Path())
		for _, p := range importPackages {
			contents.importsMap[p] = true
		}

		if strct, ok := fieldType.Underlying().(*types.Struct); ok && types.Implements(fieldType, selSetInterface) {
			recurseParse[packageLocalName] = strct
			fmt.Fprintf(
				contents.content,
				objectFieldFormat,
				fmt.Sprintf("%s_%s", typeName, field.Name()),
				typeName,
				packageLocalName,
				fieldName,
			)
		} else {
			fmt.Fprintf(
				contents.content,
				scalarFieldFormat,
				fmt.Sprintf("%s_%s", typeName, field.Name()),
				typeName,
				fieldName,
			)
		}
	}
	for n, t := range recurseParse {
		if err := parseSelectionSet(n, pkg, contents, t); err != nil {
			return err
		}
	}
	return nil
}

func writeToFile(filename string, contents *fileContent) error {
	f, err := os.Create(filename)
	if err != nil {
		return err
	}
	defer f.Close()
	if _, err := contents.header.WriteTo(f); err != nil {
		return err
	}
	if _, err := contents.imports.WriteTo(f); err != nil {
		return err
	}
	if _, err := contents.content.WriteTo(f); err != nil {
		return err
	}
	return nil
}

func loadPackage(path string) (*types.Package, error) {
	cfg := &packages.Config{Mode: packages.NeedName | packages.NeedTypes | packages.NeedTypesInfo, Tests: true}
	pkgs, err := packages.Load(cfg, path)
	if err != nil {
		return nil, fmt.Errorf("couldn't load package: %v", err)
	}
	//	if packages.PrintErrors(pkgs) > 0 {
	//		return nil, fmt.Errorf("package contains errors")
	//	}
	return pkgs[0].Types, nil
}

func parseFieldTypeName(name, rootPkgPath string) (importPackages []string, typeName string) {
	genericTypeRegex := re.MustCompile(`^(.*?)(\[(.*)\])?$`)
	genericMatches := genericTypeRegex.FindStringSubmatch(name)

	rgx := re.MustCompile(`^(\[\])?(\*)?((?:.*/)?(.*))\.(.*)$`)
	matches := rgx.FindStringSubmatch(genericMatches[1])
	// basic types: int, string, etc
	if len(matches) == 0 {
		return nil, name
	}
	importPackages = []string{}
	array := matches[1]
	pointer := matches[2]
	typePackagePath := matches[3]
	typePackageName := matches[4]
	typeName = matches[5]
	// if type has generic type parameters
	if genericMatches[2] != "" {
		typeParams := strings.Split(genericMatches[3], ", ")
		typeParamNames := []string{}
		for _, tp := range typeParams {
			tpImportPackages, tpTypeName := parseFieldTypeName(tp, rootPkgPath)
			importPackages = append(importPackages, tpImportPackages...)
			typeParamNames = append(typeParamNames, tpTypeName)
		}
		typeName = fmt.Sprintf("%s[%s]", typeName, strings.Join(typeParamNames, ", "))
	}
	// if type's source pkg is not the same as root package, import
	if rootPkgPath == typePackagePath {
		return importPackages, fmt.Sprintf("%s%s%s", array, pointer, typeName)
	}
	importPackages = append(importPackages, matches[3])
	return importPackages, fmt.Sprintf("%s%s%s.%s", array, pointer, typePackageName, typeName)
}

var (
	eywaPkg *types.Package

	selSetInterface *types.Interface
	argSetInterface *types.Interface
)

func loadEywaInterfaces() error {
	var err error
	if eywaPkg == nil {
		eywaPkg, err = loadPackage("..")
		if err != nil {
			return err
		}
	}

	selSetObj := eywaPkg.Scope().Lookup("SelectionSet")
	if selSetObj == nil {
		return errors.New("SelectionSet interface not found")
	}
	argSetObj := eywaPkg.Scope().Lookup("ArgumentSet")
	if argSetObj == nil {
		return errors.New("ArgumentSet interface not found")
	}

	selSetInterface = selSetObj.Type().Underlying().(*types.Interface)
	argSetInterface = argSetObj.Type().Underlying().(*types.Interface)
	return nil
}
